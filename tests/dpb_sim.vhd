 function init return memory_t is
  variable m:memory_t;
 begin
  for i in 0 to 2047 loop
   m(i):=to_stdlogicvector(chunks(i/32)((i mod 32)*8+7 downto (i mod 32)*8));
  end loop;
  return m;
 end;
 signal memory:memory_t:=init;
begin
 assert BIT_WIDTH_0=8 and BIT_WIDTH_1=8 and READ_MODE0='0' and READ_MODE1='0'
  report "Unsupported DPB simulation mode" severity failure;
 process(CLKA,CLKB)
  variable a,b:natural;
 begin
  if rising_edge(CLKA) then
   if CEA='1' and BLKSELA=to_stdlogicvector(BLK_SEL_0) then
    a:=to_integer(unsigned(ADA(13 downto 3)));
    if WREA='1' then
     memory(a)<=DIA(7 downto 0);DOA<=x"00" & DIA(7 downto 0);
    else DOA<=x"00" & memory(a);end if;
   end if;
  end if;
  if rising_edge(CLKB) then
   assert WREB='0' report "Simulation model expects read-only B" severity failure;
   if CEB='1' and BLKSELB=to_stdlogicvector(BLK_SEL_1) then
    b:=to_integer(unsigned(ADB(13 downto 3)));DOB<=x"00" & memory(b);
   end if;
  end if;
 end process;
